/**
 * Downloads a CSV tax summary covering completed trips + logged driver expenses.
 */
export function exportTaxSummaryCsv(
  trips: CompletedTrip[],
  expenses: DriverExpense[],
  currency: string
): void {
  const escCsv = (val: string | number) => `"${String(val).replace(/"/g, '""')}"`;
  const lines: string[] = [
    `Bolt Driver Tax Summary (${currency.trim()})`,
    '',
    'TRIPS',
    'Trip ID,Day,Time,Category,Payment,Pickup,Dropoff,Distance (km),Duration (min),Base Fare,Distance Fare,Time Fare,Surge Bonus,Wait Fee,Gross Fare,Commission (15%),Tip,Net Earnings',
  ];

  for (const t of trips) {
    lines.push(
      [
        t.id,
        t.dayKey,
        t.completedAt,
        t.category,
        t.paymentMethod,
        t.pickupAddress,
        t.dropoffAddress,
        t.distanceKm.toFixed(1),
        t.durationMin,
        t.baseFare.toFixed(2),
        t.distanceFare.toFixed(2),
        t.timeFare.toFixed(2),
        t.surgeBonus.toFixed(2),
        t.waitFee.toFixed(2),
        t.grossFare.toFixed(2),
        t.boltCommission.toFixed(2),
        t.tip.toFixed(2),
        t.netEarnings.toFixed(2),
      ]
        .map(escCsv)
        .join(',')
    );
  }

  lines.push('', 'EXPENSES', 'Expense ID,Day,Date,Category,Note,Amount');
  for (const e of expenses) {
    lines.push([e.id, e.dayKey, e.dateLabel, e.category, e.note, e.amount.toFixed(2)].map(escCsv).join(','));
  }

  const grossNet = trips.reduce((s, t) => s + t.netEarnings, 0);
  const totalExp = expenses.reduce((s, e) => s + e.amount, 0);
  lines.push('', `Total Net Trip Payouts,${grossNet.toFixed(2)}`);
  lines.push(`Total Deductible Expenses,${totalExp.toFixed(2)}`);
  lines.push(`True Net Profit,${(grossNet - totalExp).toFixed(2)}`);

  const blob = new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `bolt-driver-tax-summary-${new Date().toISOString().split('T')[0]}.csv`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
