import { CompletedTrip, DriverExpense, DriverProfile, Vehicle } from '../types/driver';

function escapePdfText(input: string): string {
  return input
    .replace(/[^\x20-\x7E]/g, (ch) => {
      if (ch === '£') return 'GBP ';
      if (ch === '€') return 'EUR ';
      if (ch === 'zł') return 'PLN ';
      if (ch === '→') return '->';
      if (ch === '·') return '-';
      return ' ';
    })
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function formatMoneyAscii(currency: string, amount: number): string {
  const c = currency.trim();
  const code = c === '£' ? 'GBP ' : c === '€' ? 'EUR ' : c === 'zł' ? 'PLN ' : `${c} `;
  return `${code}${amount.toFixed(2)}`;
}

/**
 * Generates a valid single-page PDF 1.4 receipt file with Bolt Driver breakdown
 * (Base fare, Distance, Time, Surge, Wait fee, Platform commission, Tip, Net payout)
 * and triggers an immediate download without needing popups.
 */
export function downloadTripPdfReceipt(
  trip: CompletedTrip,
  profile: DriverProfile,
  vehicle: Vehicle,
  currency: string
): void {
  const commands: string[] = [];
  let y = 780;

  const drawText = (
    text: string,
    x: number,
    size = 10,
    bold = false,
    color: [number, number, number] = [0.08, 0.1, 0.14]
  ) => {
    const font = bold ? '/F2' : '/F1';
    commands.push(
      `BT ${font} ${size} Tf ${color[0]} ${color[1]} ${color[2]} rg ${x} ${y} Td (${escapePdfText(
        text
      )}) Tj ET`
    );
  };

  const drawLine = (yPos: number, rgb: [number, number, number] = [0.86, 0.89, 0.92]) => {
    commands.push(`${rgb[0]} ${rgb[1]} ${rgb[2]} RG 0.8 w 48 ${yPos} m 547 ${yPos} l S`);
  };

  // Header Banner
  commands.push('0.05 0.09 0.13 rg 48 732 499 68 re f');
  commands.push('0.2 0.82 0.53 rg 48 796 499 4 re f');
  y = 770;
  drawText('BOLT DRIVER PARTNER RECEIPT', 64, 16, true, [1, 1, 1]);
  y = 750;
  drawText(
    `Receipt ID: ${trip.id}   |   ${trip.dayKey} ${trip.completedAt}   |   ${trip.category}`,
    64,
    9.5,
    false,
    [0.78, 0.84, 0.88]
  );

  y = 708;
  drawText('DRIVER & VEHICLE DETAILS', 48, 9, true, [0.4, 0.45, 0.52]);
  y -= 16;
  drawText(`Driver: ${profile.fullName}`, 48, 10.5, true);
  drawText(`Vehicle: ${vehicle.makeModel} (${vehicle.plate})`, 300, 10.5, false);
  y -= 16;
  drawText(`Rider: ${trip.riderName}`, 48, 10, false);
  drawText(`Payment Method: ${trip.paymentMethod}`, 300, 10, false);

  y -= 14;
  drawLine(y);
  y -= 20;

  drawText('TRIP ROUTE SUMMARY', 48, 9, true, [0.4, 0.45, 0.52]);
  y -= 16;
  drawText(`Pickup:  ${trip.pickupAddress}`, 48, 10, false);
  y -= 15;
  if (trip.stopsCount && trip.stopsCount > 0) {
    drawText(`Stops:   ${trip.stopsCount} intermediate stop(s) completed`, 48, 10, false);
    y -= 15;
  }
  drawText(`Dropoff: ${trip.dropoffAddress}`, 48, 10, false);
  y -= 15;
  drawText(
    `Distance: ${trip.distanceKm.toFixed(1)} km   |   Duration: ${trip.durationMin} min`,
    48,
    9.5,
    false,
    [0.35, 0.4, 0.48]
  );

  y -= 14;
  drawLine(y);
  y -= 22;

  drawText('ITEMIZED FARE BREAKDOWN', 48, 9, true, [0.4, 0.45, 0.52]);
  y -= 20;

  const addRow = (label: string, value: string, bold = false, color?: [number, number, number]) => {
    drawText(label, 48, 10.5, bold, color || [0.1, 0.12, 0.16]);
    drawText(value, 430, 10.5, bold, color || [0.1, 0.12, 0.16]);
    y -= 18;
  };

  addRow('Base Fare', formatMoneyAscii(currency, trip.baseFare));
  addRow(`Distance Fare (${trip.distanceKm.toFixed(1)} km)`, formatMoneyAscii(currency, trip.distanceFare));
  addRow(`Time Fare (${trip.durationMin} min)`, formatMoneyAscii(currency, trip.timeFare));
  if (trip.surgeBonus > 0) {
    addRow(
      `Surge Multiplier (${(trip.surgeMultiplier || 1.2).toFixed(1)}x)`,
      `+${formatMoneyAscii(currency, trip.surgeBonus)}`,
      false,
      [0.75, 0.4, 0.05]
    );
  } else {
    addRow('Surge Bonus', formatMoneyAscii(currency, 0));
  }
  if (trip.waitFee > 0) {
    addRow('Paid Pickup Wait Fee', `+${formatMoneyAscii(currency, trip.waitFee)}`);
  }

  y -= 2;
  drawLine(y);
  y -= 18;
  addRow('Gross Rider Fare', formatMoneyAscii(currency, trip.grossFare), true);
  addRow(
    'Bolt Platform Commission (15%)',
    `-${formatMoneyAscii(currency, trip.boltCommission)}`,
    false,
    [0.76, 0.16, 0.24]
  );
  if (trip.tip > 0) {
    addRow('Rider Tip (0% commission)', `+${formatMoneyAscii(currency, trip.tip)}`, false, [0.08, 0.58, 0.34]);
  }

  y -= 4;
  commands.push('0.93 0.98 0.95 rg 48 ' + (y - 12) + ' 499 34 re f');
  y += 2;
  drawText('NET DRIVER PAYOUT', 60, 12, true, [0.06, 0.18, 0.12]);
  drawText(formatMoneyAscii(currency, trip.netEarnings), 425, 13, true, [0.08, 0.56, 0.34]);

  y -= 36;
  if (trip.incidentNote) {
    drawText(`Safety / Incident Note: ${trip.incidentNote}`, 48, 9, false, [0.65, 0.2, 0.2]);
    y -= 16;
  }

  drawLine(90);
  y = 74;
  drawText(
    'Generated by Bolt Driver Companion · Tax & accounting summary for partner records.',
    48,
    8.5,
    false,
    [0.45, 0.5, 0.56]
  );

  const streamContent = commands.join('\n');
  const objects = [
    '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n',
    '2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj\n',
    '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >> endobj\n',
    `4 0 obj << /Length ${streamContent.length} >>\nstream\n${streamContent}\nendstream\nendobj\n`,
    '5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj\n',
    '6 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >> endobj\n',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [0];
  for (const obj of objects) {
    offsets.push(pdf.length);
    pdf += obj;
  }

  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i < offsets.length; i++) {
    pdf += `${offsets[i].toString().padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer << /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  const blob = new Blob([pdf], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `bolt-receipt-${trip.id.toLowerCase()}.pdf`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 2500);
}

